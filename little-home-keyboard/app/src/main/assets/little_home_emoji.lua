return function(input, env)
  local context = env.engine.context
  local enabled = not context:get_option("ascii_mode") and not context:get_option("home_emoji_off")
  local originals, count, seen = 0, 0, {}
  for candidate in input:iter() do
    yield(candidate)
    originals = originals + 1
    if enabled and originals <= 5 and count < 3 then
      local matches = words[candidate.text]
      if matches then
        for _, text in ipairs(matches) do
          if count < 3 and not seen[text] then
            seen[text] = true
            local emoji = Candidate("home_emoji", candidate.start, candidate._end, text, "")
            emoji.quality = candidate.quality or 0
            yield(emoji)
            count = count + 1
          end
        end
      end
    end
  end
end
